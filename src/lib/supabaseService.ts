/**
 * Generate a real, valid, multi-line PDF Document as a data URI
 * Uses encodeURIComponent (zero btoa calls) so it is 100% Unicode-safe.
 */
export function createSamplePdfDataUrl(
  title: string,
  subtitle: string,
  bulletPoints: string[]
): string {
  const escapePdfText = (str: string) =>
    String(str)
      .replace(/[—–]/g, '-')
      .replace(/·/g, '|')
      .replace(/[^\x20-\x7E]/g, '')
      .replace(/\\/g, '\\\\')
      .replace(/\(/g, '\\(')
      .replace(/\)/g, '\\)');

  const contentOps: string[] = [
    'BT',
    '/F1 18 Tf',
    '48 760 Td',
    `(${escapePdfText(title)}) Tj`,
    '/F1 11 Tf',
    '0 -24 Td',
    `(${escapePdfText(subtitle)}) Tj`,
    '0 -20 Td',
    '(--------------------------------------------------------------------------------) Tj'
  ];

  bulletPoints.forEach((line) => {
    contentOps.push('0 -22 Td');
    contentOps.push(`(${escapePdfText(line)}) Tj`);
  });

  contentOps.push('0 -36 Td');
  contentOps.push('(Generated by FileNest - B.Tech CSE Academic Repository) Tj');
  contentOps.push('ET');

  const streamContent = contentOps.join('\n');
  const objects = [
    '1 0 obj\n<< /Type /Catalog /Pages 2 0 R >>\nendobj\n',
    '2 0 obj\n<< /Type /Pages /Kids [3 0 R] /Count 1 >>\nendobj\n',
    '3 0 obj\n<< /Type /Page /Parent 2 0 R /Resources << /Font << /F1 4 0 R >> >> /MediaBox [0 0 612 792] /Contents 5 0 R >>\nendobj\n',
    '4 0 obj\n<< /Type /Font /Subtype /Type1 /BaseFont /Helvetica >>\nendobj\n',
    `5 0 obj\n<< /Length ${streamContent.length} >>\nstream\n${streamContent}\nendstream\nendobj\n`
  ];

  let pdf = '%PDF-1.4\n';
  const offsets = [0];
  objects.forEach((obj) => {
    offsets.push(pdf.length);
    pdf += obj;
  });

  const xrefStart = pdf.length;
  pdf += `xref\n0 ${objects.length + 1}\n0000000000 65535 f \n`;
  for (let i = 1; i <= objects.length; i++) {
    pdf += `${String(offsets[i]).padStart(10, '0')} 00000 n \n`;
  }
  pdf += `trailer\n<< /Size ${objects.length + 1} /Root 1 0 R >>\nstartxref\n${xrefStart}\n%%EOF`;

  try {
    const base64 = btoa(pdf);
    return `data:application/pdf;base64,${base64}`;
  } catch {
    return `data:application/pdf;charset=utf-8,${encodeURIComponent(pdf)}`;
  }
}

